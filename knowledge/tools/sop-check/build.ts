// Bundles sop-check (main.ts, cli.ts and the domain's pure rules in packages/domain/src/knowledge.ts) into the
// recurring-job skill's scripts/sop-check.mjs, so a copied skill runs on Node with one package installed beside it.
// yaml stays external: it is installed, with its own licence, by `npm install` in the skill's folder (the skill's
// package.json pins it), never copied in. `npm run knowledge:build` writes the file; a test holds it equal to a fresh build.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = resolve(import.meta.dirname, "../../..");
export const OUT = join(ROOT, "knowledge/skills/recurring-job/scripts/sop-check.mjs");
const BANNER = [
  "#!/usr/bin/env node",
  "// Generated by `npm run knowledge:build` from knowledge/tools/sop-check and packages/domain/src/knowledge.ts. Don't edit.",
  "// AGPL-3.0: LICENSE.md in the Morndo repository. Needs Node 20 or later and the yaml package: npm install in this skill's folder.",
].join("\n");

export async function bundle(): Promise<string> {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: ["knowledge/tools/sop-check/main.ts"],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    external: ["yaml"],
    banner: { js: BANNER },
    legalComments: "none",
    write: false,
  });
  return result.outputFiles[0]?.text ?? "";
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, await bundle());
}
