#!/bin/sh
# Proves commit-traces and the commit-msg hook. Identity is set only on the
# git command, inside this throwaway repository. One check runs the pre-push
# hook itself, so its own selection, not a hand-written rev-list, decides
# which commits are re-checked.
set -eu

root=$(git rev-parse --show-toplevel)
checker=$root/scripts/git-hooks/commit-traces
hook=$root/scripts/git-hooks/commit-msg
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }

msg=$scratch/msg
printf '%s\n' 'fix: clean note' > "$msg"
sh "$checker" message "$msg" || fail "clean message should exit 0"

printf '%s\n\n%s\n' 'fix: clean note' 'Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>' > "$msg"
sh "$checker" message "$msg" || fail "dependabot trailer should exit 0"

bad_line() {
  label=$1
  body=$2
  printf '%s\n' "$body" > "$msg"
  set +e
  sh "$checker" message "$msg"
  code=$?
  set -e
  [ "$code" -eq 1 ] || fail "$label should exit 1, got $code"
}

printf '%s\n#\tnew file: runtime-codex.ts\n' 'fix: tweak runtime' > "$msg"
sh "$checker" message "$msg" || fail "a comment line should be ignored"
printf '%s\n# ------------------------ >8 ------------------------\n+runtime-codex\n' 'fix: tweak runtime' > "$msg"
sh "$checker" message "$msg" || fail "text after the scissors line should be ignored"

bad_line "generated with" "$(printf '%s\n\n%s %s %s\n' 'fix: clean note' Generated with Example)"
bad_line "robot emoji" "$(printf 'fix: clean note %s\n' "$(printf '\360\237\244\226')")"
printf '%s\n' 'fix(connections): start the claude runtime without a base URL' > "$msg"
sh "$checker" message "$msg" || fail "a runtime name in the subject should exit 0"
bad_line "assistant trailer" "$(printf '%s\n\nCo-authored-by: %s <a@example.invalid>\n' 'fix: clean note' 'Claude')"
bad_line "generated by" "$(printf '%s\n\n%s %s %s\n' 'fix: clean note' Generated by Example)"
bad_line "vendor mail" "fix: clean note <dev@anthropic.com>"
bad_line "chat link" "fix: clean note https://claude.ai/chat/abc"
bad_line "other bot trailer" "$(printf '%s\n\nCo-authored-by: %s <b@example.invalid>\n' 'fix: clean note' 'review[bot]')"

git init -q "$scratch/repo"
cd "$scratch/repo"
ln -sfn "$hook" .git/hooks/commit-msg
git -c user.name=Ada -c user.email=ada@users.noreply.github.com commit -q --allow-empty -m 'fix: clean note' \
  || fail "hook should allow a clean message"
git -c user.name='dependabot[bot]' -c user.email='49699333+dependabot[bot]@users.noreply.github.com' \
  commit -q --allow-empty -m 'chore: bump a fixture' || fail "hook should allow dependabot[bot]"

set +e
git -c user.name=Ada -c user.email=ada@users.noreply.github.com commit -q --allow-empty -m "$(printf 'fix: clean note\n\nGenerated with Example')"
code=$?
set -e
[ "$code" -ne 0 ] || fail "hook should reject a generated-with message"

parent=$(git rev-parse HEAD)
git -c user.name='claude[bot]' -c user.email=bot@users.noreply.github.com commit -q --allow-empty -m 'fix: clean note' \
  || fail "hook checks the message only; a bot author is a CI check"
tip=$(git rev-parse HEAD)
set +e
sh "$checker" range "$parent..$tip"
code=$?
set -e
[ "$code" -eq 1 ] || fail "bot author should exit 1, got $code"

git -c user.name='copilot-swe-agent' -c user.email=swe@users.noreply.github.com commit -q --allow-empty -m 'fix: clean note'
tip=$(git rev-parse HEAD)
set +e
sh "$checker" range "$parent..$tip"
code=$?
set -e
[ "$code" -eq 1 ] || fail "agent author should exit 1, got $code"

set +e
sh "$checker" range HEAD
code=$?
set -e
[ "$code" -eq 1 ] || fail "range including a bot author should exit 1, got $code"

mail_base=$(git rev-parse HEAD)
env GIT_AUTHOR_EMAIL=ada@example.invalid git -c user.name=Ada -c user.email=ada@users.noreply.github.com \
  commit -q --allow-empty -m 'fix: clean note'
tip=$(git rev-parse HEAD)
set +e
sh "$checker" range "$mail_base..$tip"
code=$?
set -e
[ "$code" -eq 1 ] || fail "author email should exit 1, got $code"
git reset -q --hard "$mail_base"
env GIT_COMMITTER_EMAIL=ada@example.invalid git -c user.name=Ada -c user.email=ada@users.noreply.github.com \
  commit -q --allow-empty -m 'fix: clean note'
tip=$(git rev-parse HEAD)
set +e
sh "$checker" range "$mail_base..$tip"
code=$?
set -e
[ "$code" -eq 1 ] || fail "committer email should exit 1, got $code"
git reset -q --hard "$mail_base"
env GIT_COMMITTER_EMAIL=noreply@github.com git -c user.name=Ada -c user.email=ada@users.noreply.github.com \
  commit -q --allow-empty -m 'fix: clean note'
tip=$(git rev-parse HEAD)
sh "$checker" range "$mail_base..$tip" || fail "web-flow committer should exit 0"
git reset -q --hard "$mail_base"
env GIT_AUTHOR_EMAIL=noreply@github.com git -c user.name=Ada -c user.email=ada@users.noreply.github.com \
  commit -q --allow-empty -m 'fix: clean note'
tip=$(git rev-parse HEAD)
set +e
sh "$checker" range "$mail_base..$tip"
code=$?
set -e
[ "$code" -eq 1 ] || fail "web-flow author should exit 1, got $code"

# The pre-push hook's own selection decides what is re-checked. The history
# is fresh and holds exactly one bad commit, so a failure can only come from
# it: bare, the range fails; published on a second remote only, the hook
# still fails it; published on the remote being pushed to, the hook passes.
zero=0000000000000000000000000000000000000000
git init -q "$scratch/sel"
cp "$root/.gitleaks.toml" "$scratch/sel/.gitleaks.toml"
cd "$scratch/sel"
git remote add origin "$scratch/sel-origin.git"
git remote add mirror "$scratch/sel-mirror.git"
printf 'ok\n' > readme.txt
git add readme.txt .gitleaks.toml
git -c user.name=Ada -c user.email=ada@users.noreply.github.com commit -q -m 'sel base'
base=$(git rev-parse HEAD)
env GIT_AUTHOR_EMAIL=ada@example.invalid git -c user.name=Ada \
  -c user.email=ada@users.noreply.github.com commit -q --allow-empty -m 'sel published'
published=$(git rev-parse HEAD)
git -c user.name=Ada -c user.email=ada@users.noreply.github.com commit -q --allow-empty -m 'sel clean'
tip=$(git rev-parse HEAD)
set +e
sh "$checker" mails "$tip"
code=$?
set -e
[ "$code" -eq 1 ] || fail "the bare history should fail on its only bad commit, got $code"
git update-ref refs/remotes/origin/main "$base"
git update-ref refs/remotes/mirror/main "$published"
set +e
printf '%s %s %s %s\n' refs/heads/main "$tip" refs/heads/main "$zero" | sh "$root/scripts/git-hooks/pre-push" origin >/dev/null 2>&1
code=$?
set -e
[ "$code" -eq 1 ] || fail "a bad commit a second remote holds should fail through the hook, got $code"
git update-ref refs/remotes/origin/main "$published"
set +e
printf '%s %s %s %s\n' refs/heads/main "$tip" refs/heads/main "$zero" | sh "$root/scripts/git-hooks/pre-push" origin >/dev/null 2>&1
code=$?
set -e
[ "$code" -eq 0 ] || fail "a bad commit the pushed-to remote holds should pass through the hook, got $code"

cd "$root"
set +e
out=$(sh "$checker" range deadbeef..HEAD 2>&1)
code=$?
set -e
[ "$code" -ne 0 ] || fail "a bad range should exit non-zero"
printf '%s\n' "$out" | grep -q 'unknown revision' || fail "a bad range should report the git error"
printf '%s\n' "$out" | grep -q 'revision range' || fail "a bad range should fail the check"

echo "commit-traces proof ok"
